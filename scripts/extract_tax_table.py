#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = ["pypdf", "fontTools"]
# ///
"""extract_tax_table.py — transcribe the IRS Tax Table into a bend check file.

Reads the official Tax Table PDF (the i1040tt instructions document),
extracts every row (all four filing-status columns), and generates
bend/TAX_TABLE_CHECK.bend, which asserts on every gate run that the
engine's Tax Table implementation reproduces the PUBLISHED value for
every row (at both row endpoints), for every status with a tables
module. The generated file is committed, so the gate needs no PDF;
re-run this script only to re-transcribe a new year's table.

The fit this verifies (midpoint a+w/2 of the row [a, a+w), rounded
half-up to the nearest dollar) reproduces all 2,062 published rows of
the 2024 table exactly.

Usage:
  uv run scripts/extract_tax_table.py <tax-table.pdf> [> /dev/null]
Writes bend/TAX_TABLE_CHECK.bend in place.
"""

from pathlib import Path
import re
import sys

import pypdf  # provided by the script header above

ROW = re.compile(r"^([\d,]+)\s+([\d,]+)\s+([\d,]+)\s+([\d,]+)\s+([\d,]+)\s+([\d,]+)$")

# alias | tables module | column index in the extracted 6-tuple (after a, b)
STATUSES = [
    ("S", "tables_2024_single", 2),
    ("M", "tables_2024_mfj", 3),
    ("FS", "tables_2024_mfs", 4),
    ("H", "tables_2024_hoh", 5),
]


def extract_rows(pdf_path: str) -> list[tuple[int, int, int, int, int, int]]:
    reader = pypdf.PdfReader(pdf_path)
    rows: list[tuple[int, int, int, int, int, int]] = []
    for page in reader.pages:
        for line in (page.extract_text() or "").splitlines():
            m = ROW.match(line.strip())
            if m:
                rows.append(tuple(int(x.replace(",", "")) for x in m.groups()))  # type: ignore[arg-type]
    rows.sort(key=lambda r: r[0])
    if not rows:
        sys.exit("facts: error: no Tax Table rows found — is that the i1040tt PDF?")
    if rows[0][0] != 0 or rows[-1][1] != 100000:
        sys.exit(f"facts: error: rows span {rows[0][0]}–{rows[-1][1]}, expected 0–100000")
    gaps = [(p, q) for p, q in zip(rows, rows[1:]) if p[1] != q[0]]
    if gaps:
        sys.exit(f"facts: error: {len(gaps)} gaps in the extracted row grid, first: {gaps[0]}")
    return rows


def generate(rows, source: str) -> str:
    out = []
    out.append("import Base")
    out.append("import ./tables_2024.bend as Y")
    for alias, module, _ in STATUSES:
        out.append(f"import ./{module}.bend as {alias}")
    out.append("import ./tax.bend as T")
    out.append("")
    out.append("# " + "=" * 76)
    out.append("# TAX_TABLE_CHECK.bend — GENERATED FILE, DO NOT EDIT.")
    out.append(f"# Generated by scripts/extract_tax_table.py from: {source}")
    out.append(f"# {len(rows)} published Tax Table rows (TI 0–100,000); every row is")
    out.append("# checked at BOTH endpoints (value + flatness) for each status with")
    out.append("# a tables module. This is the paper table itself, as data.")
    out.append("# Checks are chunked into blocks — a single 8k-deep IO do-chain")
    out.append("# overflows the runtime's stack.")
    out.append("# " + "=" * 76)
    out.append("")
    out.append('def ck_b(name: String, +got: Nat, +want: Nat, +ok: Bool) -> IO(Unit):')
    out.append("  match ok:")
    out.append("    case True{}:")
    out.append('      IO.print("PASS " ++ name ++ "\\n")')
    out.append("    case False{}:")
    out.append('      IO.print("FAIL " ++ name ++ ": got " ++ Nat.show(got) ++ ", want " ++ Nat.show(want) ++ "\\n")')
    out.append("")
    out.append("def ck(+name: String, +got: Nat, +want: Nat) -> IO(Unit):")
    out.append("  ck_b(name, got, want, Nat.is_eq(got, want))")
    out.append("")

    # chunk the checks so no single IO do-chain gets too deep
    checks = []
    for a, b, *vals in rows:
        for alias, _, col in STATUSES:
            v = vals[col - 2]
            checks.append(f'    ck("{alias} TI {a} [{a}-{b}]", T.ordinary_tax_tiled({a}n, {alias}.tables()), {v}n)')
            checks.append(f'    ck("{alias} TI {b - 1} [{a}-{b}]", T.ordinary_tax_tiled({b - 1}n, {alias}.tables()), {v}n)')
    CHUNK = 500
    blocks = [checks[i:i + CHUNK] for i in range(0, len(checks), CHUNK)]
    for bi, block in enumerate(blocks):
        out.append(f"def block_{bi}() -> IO(Unit):")
        out.append("  do IO<Unit>:")
        out.extend(block)
        out.append("")
    out.append("def main() -> IO(Unit):")
    out.append("  do IO<Unit>:")
    for bi in range(len(blocks)):
        out.append(f"    block_{bi}()")
    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: extract_tax_table.py <i1040tt.pdf>")
    source = Path(sys.argv[1]).name
    rows = extract_rows(sys.argv[1])
    out_path = Path(__file__).resolve().parent.parent / "bend" / "TAX_TABLE_CHECK.bend"
    out_path.write_text(generate(rows, source), encoding="utf-8")
    checks = len(rows) * 2 * len(STATUSES)
    print(f"extract_tax_table: wrote {out_path} ({len(rows)} rows, {checks} checks)")


if __name__ == "__main__":
    main()
